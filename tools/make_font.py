#!/usr/bin/env python3
"""Render a TrueType font into a 1-bit glyph table for the e-ink firmware.

    python3 tools/make_font.py FONT.ttf SIZE C_NAME OUT.c

Glyphs are rendered without anti-aliasing (crisp on e-paper), cropped to their
ink, and stored row by row, each row padded to whole bytes, MSB = leftmost
pixel. Covers ASCII, Latin-1 and the punctuation Claude tends to use
(curly quotes, dashes, ellipsis, bullet, euro).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

CODEPOINTS = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC]
)


def render(font_path, size):
    font = ImageFont.truetype(font_path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for cp in CODEPOINTS:
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        canvas = Image.new("1", (size * 4, size * 4), 0)
        draw = ImageDraw.Draw(canvas)
        draw.fontmode = "1"  # no anti-aliasing
        ox, oy = size, size * 3  # pen position on the baseline
        draw.text((ox, oy), ch, font=font, fill=1, anchor="ls")
        bbox = canvas.getbbox()
        if bbox is None:  # space, no-break space
            glyphs.append((cp, 0, 0, 0, 0, adv, b""))
            continue
        x0, y0, x1, y1 = bbox
        rows = bytearray()
        for y in range(y0, y1):
            byte, nbits = 0, 0
            for x in range(x0, x1):
                byte = (byte << 1) | (1 if canvas.getpixel((x, y)) else 0)
                nbits += 1
                if nbits == 8:
                    rows.append(byte)
                    byte, nbits = 0, 0
            if nbits:
                rows.append(byte << (8 - nbits))
        glyphs.append((cp, x1 - x0, y1 - y0, x0 - ox, y0 - oy, adv, bytes(rows)))
    return glyphs, ascent, descent


def emit(glyphs, ascent, descent, c_name, src_desc):
    out = [
        f"// Generated by tools/make_font.py from {src_desc}. Do not edit by hand.",
        "// DejaVu fonts: Bitstream Vera licence with public-domain changes,",
        "// https://dejavu-fonts.github.io/License.html",
        '#include "font.h"',
        "",
        f"static const uint8_t {c_name}_bitmap[] = {{",
    ]
    offsets, offset, line = [], 0, []
    for g in glyphs:
        offsets.append(offset)
        for b in g[6]:
            line.append(f"0x{b:02x}")
            if len(line) == 16:
                out.append("    " + ", ".join(line) + ",")
                line = []
        offset += len(g[6])
    if line:
        out.append("    " + ", ".join(line) + ",")
    if offset == 0:
        out.append("    0x00,")
    out.append("};")
    out.append("")
    out.append(f"static const glyph_t {c_name}_glyphs[] = {{")
    out.append("    // code point, offset, w, h, xoff, yoff, advance")
    for g, off in zip(glyphs, offsets):
        cp, w, h, xoff, yoff, adv, _ = g
        out.append(f"    {{0x{cp:04x}, {off}, {w}, {h}, {xoff}, {yoff}, {adv}}},")
    out.append("};")
    out.append("")
    out.append(f"const font_t {c_name} = {{")
    out.append(f"    .bitmap = {c_name}_bitmap,")
    out.append(f"    .glyphs = {c_name}_glyphs,")
    out.append(f"    .count = {len(glyphs)},")
    out.append(f"    .line_height = {ascent + descent},")
    out.append(f"    .ascent = {ascent},")
    out.append("};")
    return "\n".join(out) + "\n", offset


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    font_path, size, c_name, out_path = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    glyphs, ascent, descent = render(font_path, size)
    desc = f"{os.path.basename(font_path)} at {size} px"
    text, nbytes = emit(glyphs, ascent, descent, c_name, desc)
    with open(out_path, "w") as f:
        f.write(text)
    print(f"{out_path}: {len(glyphs)} glyphs, {nbytes} bitmap bytes, line height {ascent + descent}")


if __name__ == "__main__":
    main()
